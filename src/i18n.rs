#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum LanguageChoice {
    #[default]
    Auto,
    En,
    PtBr,
    Es,
    Fr,
    De,
    It,
    Ja,
    ZhCn,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Language {
    En,
    PtBr,
    Es,
    Fr,
    De,
    It,
    Ja,
    ZhCn,
}

impl LanguageChoice {
    pub const ALL: &'static [LanguageChoice] = &[
        LanguageChoice::Auto,
        LanguageChoice::En,
        LanguageChoice::PtBr,
        LanguageChoice::Es,
        LanguageChoice::Fr,
        LanguageChoice::De,
        LanguageChoice::It,
        LanguageChoice::Ja,
        LanguageChoice::ZhCn,
    ];

    pub fn resolve(self) -> Language {
        match self {
            LanguageChoice::Auto => detect_os_language(),
            LanguageChoice::En => Language::En,
            LanguageChoice::PtBr => Language::PtBr,
            LanguageChoice::Es => Language::Es,
            LanguageChoice::Fr => Language::Fr,
            LanguageChoice::De => Language::De,
            LanguageChoice::It => Language::It,
            LanguageChoice::Ja => Language::Ja,
            LanguageChoice::ZhCn => Language::ZhCn,
        }
    }

    pub fn display_label(self) -> &'static str {
        match self {
            LanguageChoice::Auto => "Auto (System)",
            LanguageChoice::En => "English",
            LanguageChoice::PtBr => "Português (Brasil)",
            LanguageChoice::Es => "Español",
            LanguageChoice::Fr => "Français",
            LanguageChoice::De => "Deutsch",
            LanguageChoice::It => "Italiano",
            LanguageChoice::Ja => "日本語",
            LanguageChoice::ZhCn => "简体中文",
        }
    }

    pub fn localized_label(self, tr: &Strings) -> &'static str {
        match self {
            LanguageChoice::Auto => tr.lang_auto_system,
            _ => self.display_label(),
        }
    }
}

pub fn detect_os_language() -> Language {
    for var in ["LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"] {
        if let Ok(val) = env::var(var)
            && let Some(lang) = parse_locale_string(&val)
        {
            return lang;
        }
    }
    Language::En
}

pub fn parse_locale_string(locale: &str) -> Option<Language> {
    for part in locale.split(':') {
        let trimmed = part.trim();
        if trimmed.is_empty()
            || trimmed.eq_ignore_ascii_case("C")
            || trimmed.starts_with("C.")
            || trimmed.eq_ignore_ascii_case("POSIX")
        {
            continue;
        }
        let clean = trimmed
            .split('.')
            .next()
            .unwrap_or(trimmed)
            .to_ascii_lowercase();
        let base = clean.split(['_', '-']).next().unwrap_or(&clean);
        match base {
            "pt" => return Some(Language::PtBr),
            "es" => return Some(Language::Es),
            "fr" => return Some(Language::Fr),
            "de" => return Some(Language::De),
            "it" => return Some(Language::It),
            "ja" => return Some(Language::Ja),
            "zh" => return Some(Language::ZhCn),
            "en" => return Some(Language::En),
            _ => {}
        }
    }
    None
}

